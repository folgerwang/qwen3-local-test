# Generates src/unicode_tables.h: code point ranges for \p{L}, \p{M}, \p{N} and White_Space,
# plus NFC data (canonical decompositions, combining classes, composition exclusions).
import sys, unicodedata

def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = pred(cp)
        if ok and start is None: start = cp
        if not ok and start is not None: out.append((start, cp - 1)); start = None
    if start is not None: out.append((start, 0x10FFFF))
    return out

def cat(prefix):
    return lambda cp: unicodedata.category(chr(cp)).startswith(prefix)

WS = [(0x09, 0x0D), (0x20, 0x20), (0x85, 0x85), (0xA0, 0xA0), (0x1680, 0x1680), (0x2000, 0x200A),
      (0x2028, 0x2029), (0x202F, 0x202F), (0x205F, 0x205F), (0x3000, 0x3000)]

def emit_ranges(f, name, rs):
    f.write(f"static const uint32_t {name}[][2] = {{\n")
    for i in range(0, len(rs), 6):
        f.write("    " + " ".join(f"{{0x{a:X}, 0x{b:X}}}," for a, b in rs[i:i + 6]) + "\n")
    f.write("};\n\n")

# NFC: canonical decomposition mappings (single level), combining classes, primary composites.
decomp, ccc = [], []
for cp in range(0x110000):
    c = chr(cp)
    if 0xAC00 <= cp <= 0xD7A3: continue  # Hangul handled algorithmically
    d = unicodedata.decomposition(c)
    if d and not d.startswith('<'):
        decomp.append((cp, [int(x, 16) for x in d.split()]))
    k = unicodedata.combining(c)
    if k: ccc.append((cp, k))
# composition pairs: a canonical pair decomposition whose recomposition is allowed by NFC
comp = []
for cp, parts in decomp:
    if len(parts) == 2 and unicodedata.normalize('NFC', ''.join(map(chr, parts))) == chr(cp):
        comp.append((parts[0], parts[1], cp))

with open(sys.argv[1], 'w', encoding='utf-8') as f:
    f.write(f"// Generated by tools/gen_unicode_tables.py from Python unicodedata {unicodedata.unidata_version}. Do not edit.\n")
    f.write("#pragma once\n#include <cstdint>\n\n")
    emit_ranges(f, "kLetter", ranges(cat('L')))
    emit_ranges(f, "kMark", ranges(cat('M')))
    emit_ranges(f, "kNumber", ranges(cat('N')))
    emit_ranges(f, "kWhiteSpace", WS)
    f.write("struct UDecomp { uint32_t cp; uint32_t a, b; };  // b == 0 for singleton\n")
    f.write("static const UDecomp kDecomp[] = {\n")
    for cp, p in decomp:
        f.write(f"    {{0x{cp:X}, 0x{p[0]:X}, 0x{(p[1] if len(p) > 1 else 0):X}}},\n")
    f.write("};\n\nstruct UCcc { uint32_t cp; uint8_t ccc; };\nstatic const UCcc kCcc[] = {\n")
    for i in range(0, len(ccc), 6):
        f.write("    " + " ".join(f"{{0x{a:X}, {b}}}," for a, b in ccc[i:i + 6]) + "\n")
    f.write("};\n\nstruct UComp { uint32_t a, b, c; };\nstatic const UComp kComp[] = {\n")
    for a, b, c in sorted(comp):
        f.write(f"    {{0x{a:X}, 0x{b:X}, 0x{c:X}}},\n")
    f.write("};\n")
